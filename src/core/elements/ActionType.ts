/**
 * Action types for element interactions
 * These define the different types of actions that can be performed on elements
 */
export enum ActionType {
  CLICK = 'click',
  DOUBLE_CLICK = 'dblclick',
  RIGHT_CLICK = 'contextmenu',
  TYPE = 'type',
  CLEAR = 'clear',
  CHECK = 'check',
  UNCHECK = 'uncheck',
  HOVER = 'hover',
  FOCUS = 'focus',
  SELECT = 'select',
  DRAG = 'drag'
}
